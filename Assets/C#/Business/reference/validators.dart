/***************************************************************************
  类名称：Validators
  功    能：提供各种表单输入验证功能，包括邮箱、密码、用户名和验证码验证
  输入参数：无
  返 回 值：无
  说    明：静态类，包含多个验证方法，用于表单输入的数据校验
***************************************************************************/
class Validators {
  /***************************************************************************
    函数名称：email
    功    能：验证邮箱地址格式是否正确
    输入参数：String? value - 待验证的邮箱地址
    返 回 值：String? - 验证失败时返回错误消息，成功时返回null
    说    明：使用正则表达式验证邮箱格式，要求包含@和域名
  ***************************************************************************/
  static String? email(String? value) {
    if (value == null || value.isEmpty) return '请输入邮箱';
    final emailRegex = RegExp(r'^[\w\.-]+@[\w\.-]+\.[a-zA-Z]{2,}');
    if (!emailRegex.hasMatch(value)) return '邮箱格式不正确';
    return null;
  }

  /***************************************************************************
    函数名称：password
    功    能：验证密码强度是否符合要求
    输入参数：String? value - 待验证的密码
    返 回 值：String? - 验证失败时返回错误消息，成功时返回null
    说    明：要求密码包含大小写字母和数字，长度至少8位
  ***************************************************************************/
  static String? password(String? value) {
    if (value == null || value.isEmpty) return '请输入密码';
    final pwdRegex = RegExp(r'^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)[A-Za-z\d]{8,}');
    if (!pwdRegex.hasMatch(value)) return '密码需包含数字、大小写字母，长度至少8位';
    return null;
  }

  /***************************************************************************
    函数名称：username
    功    能：验证用户名格式是否正确
    输入参数：String? value - 待验证的用户名
    返 回 值：String? - 验证失败时返回错误消息，成功时返回null
    说    明：要求用户名长度至少2位
  ***************************************************************************/
  static String? username(String? value) {
    if (value == null || value.isEmpty) return '请输入用户名';
    if (value.length < 2) return '用户名长度至少2位';
    return null;
  }

  /***************************************************************************
    函数名称：code
    功    能：验证验证码格式是否正确
    输入参数：String? value - 待验证的验证码
    返 回 值：String? - 验证失败时返回错误消息，成功时返回null
    说    明：要求验证码为6位数字
  ***************************************************************************/
  static String? code(String? value) {
    if (value == null || value.isEmpty) return '请输入验证码';
    if (value.length != 6) return '验证码长度为6位';
    return null;
  }
}
