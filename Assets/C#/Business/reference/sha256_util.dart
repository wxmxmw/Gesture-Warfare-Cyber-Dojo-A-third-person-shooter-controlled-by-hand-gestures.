import 'dart:convert';
import 'package:crypto/crypto.dart';

/***************************************************************************
  类 名 称：Sha256Util
  功    能：SHA256加密工具类，提供字符串的SHA256哈希值计算功能
  输入参数：无构造参数（纯静态工具类）
  返 回 值：Sha256Util类（静态方法调用）
  说    明：基于crypto包实现的SHA256哈希算法，用于生成字符串的固定长度哈希值，常用于密码加密、数据完整性验证和唯一标识生成
***************************************************************************/
class Sha256Util {
  /***************************************************************************
  函数名称：getSHA256
  功    能：计算字符串的SHA256哈希值
  输入参数：String str - 待计算哈希值的原始字符串
  返 回 值：String - 64位十六进制格式的SHA256哈希值字符串
  说    明：使用UTF-8编码将字符串转换为字节数组，然后通过SHA256算法计算哈希值并返回十六进制字符串表示。生成的哈希值具有固定长度（64个字符），相同输入产生相同输出，不可逆向解密
***************************************************************************/
  static String getSHA256(String str) {
    var bytes = utf8.encode(str);
    var digest = sha256.convert(bytes);
    return digest.toString();
  }
}
